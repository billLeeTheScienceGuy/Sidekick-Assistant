"""Owner-accept and stranger-accept rates from SidekickVoice log lines (task 8.1).

Collect one log per recording run on the phone, then label each run with who spoke and the condition:

  adb logcat -c            # before the run
  ... run a listening session ...
  adb logcat -d -s SidekickVoice:I > runs/owner-quiet-1.txt

  python scripts/phone-tests/voice_tuning_report.py \
      owner:quiet:runs/owner-quiet-1.txt  stranger:quiet:runs/p01-quiet.txt  stranger:noisy:runs/p01-noisy.txt ...
      [--out docs/evaluation/SPEAKER_TUNING_RESULTS.md]

Roles: "owner" (the enrolled phone owner speaking) or "stranger" (any other consenting participant).
Conditions: free text, e.g. quiet, noisy, far.

Privacy: SidekickVoice lines contain only the speaker decision, keep/drop, the consent rule and match scores; never
words, location, voice labels or names. This script reads only those numeric fields and refuses lines that look like
they contain anything else. Do not commit raw logs; commit only the report.
"""
import argparse
import collections
import re
import sys

LINE = re.compile(r"SidekickVoice\s*:\s*(?P<body>speaker=.*)$")
SPEAKER = re.compile(r"speaker=(USER|OTHER|UNKNOWN)")
KEPT = re.compile(r"kept=(true|false)")
THRESHOLDS = re.compile(r"thresholds (standard|before-notice)")
LONG = re.compile(r"profile ((?:-?\d\.\d\d)(?: / -?\d\.\d\d)*)")
SHORT = re.compile(r"short profile (-?\d\.\d\d); recent mean (-?\d\.\d\d); two-window support (-?\d\.\d\d)")
ALLOWED = re.compile(r"^[\w=.:;/ ,()%\-·]*$")


def parse(path):
    turns = []
    with open(path, encoding="utf-8", errors="replace") as f:
        for raw in f:
            m = LINE.search(raw.rstrip())
            if not m:
                continue
            body = m.group("body")
            if not ALLOWED.match(body):
                sys.exit(f"{path}: unexpected characters in a SidekickVoice line; refusing (logs must hold scores only)")
            speaker = SPEAKER.search(body).group(1)
            kept = KEPT.search(body)
            t = THRESHOLDS.search(body)
            long_scores = LONG.search(body.split("short profile")[0]) if "short profile" not in body else None
            short = SHORT.search(body)
            turns.append({
                "speaker": speaker,
                "kept": kept and kept.group(1) == "true",
                "thresholds": t.group(1) if t else "standard",
                "scores": [float(x) for x in long_scores.group(1).split(" / ")] if long_scores else None,
                "short": float(short.group(1)) if short else None,
            })
    return turns


def rate(n, d):
    return f"{n}/{d} ({100.0 * n / d:.1f}%)" if d else "0/0"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("runs", nargs="+", help="role:condition:path")
    ap.add_argument("--out", help="write a Markdown report here")
    args = ap.parse_args()
    groups = collections.defaultdict(list)
    participants = collections.defaultdict(set)
    for spec in args.runs:
        role, condition, path = spec.split(":", 2)
        if role not in ("owner", "stranger"):
            sys.exit(f"role must be owner or stranger: {spec}")
        groups[(role, condition)] += parse(path)
        participants[role].add(path)
    out = ["# Speaker threshold tuning results", "",
           "Generated by `scripts/phone-tests/voice_tuning_report.py` from SidekickVoice log lines (scores and keep/drop only).", "",
           f"Runs: {len(participants['owner'])} owner, {len(participants['stranger'])} stranger log files.", "",
           "## Observed decisions (as run on the phone)", "",
           "| Role | Condition | Turns | Accepted as owner | OTHER | UNKNOWN |", "| --- | --- | --- | --- | --- | --- |"]
    for (role, condition), turns in sorted(groups.items()):
        c = collections.Counter(t["speaker"] for t in turns)
        out.append(f"| {role} | {condition} | {len(turns)} | {rate(c['USER'], len(turns))} | {c['OTHER']} | {c['UNKNOWN']} |")
    out += ["", "## Threshold sweep (long turns: every window score >= threshold)", "",
            "Owner accept should be high; stranger accept must stay at 0. Short phrases (1.5-3 s) are reported separately.", "",
            "| Threshold | " + " | ".join(f"{r} {c}" for r, c in sorted(groups)) + " |",
            "| --- |" + " --- |" * len(groups)]
    for th in [x / 100 for x in range(60, 91, 5)]:
        cells = []
        for key in sorted(groups):
            scored = [t for t in groups[key] if t["scores"]]
            cells.append(rate(sum(1 for t in scored if min(t["scores"]) >= th), len(scored)))
        out.append(f"| {th:.2f} | " + " | ".join(cells) + " |")
    out += ["", "## Short phrases (profile score >= threshold)", "", "| Threshold | " + " | ".join(f"{r} {c}" for r, c in sorted(groups)) + " |",
            "| --- |" + " --- |" * len(groups)]
    for th in [x / 100 for x in range(60, 91, 5)]:
        cells = []
        for key in sorted(groups):
            scored = [t for t in groups[key] if t["short"] is not None]
            cells.append(rate(sum(1 for t in scored if t["short"] >= th), len(scored)))
        out.append(f"| {th:.2f} | " + " | ".join(cells) + " |")
    text = "\n".join(out) + "\n"
    if args.out:
        with open(args.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(text)


if __name__ == "__main__":
    main()
